/**
 * BrewMesh Queries Typegen
 * Parses sql/queries.sql and generates typed PreparedQuery runners in src/queries.ts.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSQLFile, queryASTToIR } from '@pgtyped/parser';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const queriesSqlPath = path.join(projectRoot, 'sql', 'queries.sql');
const outputTsPath = path.join(projectRoot, 'src', 'queries.ts');

/**
 * Strips single-line comments that might confuse the parser if positioned before query blocks.
 */
function sanitizeSql(sql: string): string {
	return sql.replace(/^--[^\n]*\n/gm, '\n');
}

/**
 * Capitalizes the first letter of a string.
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}

/**
 * Generates typed query definitions from sql/queries.sql.
 */
export function generateQueries(): void {
	const rawSql = fs.readFileSync(queriesSqlPath, 'utf8');
	const cleanSql = sanitizeSql(rawSql);
	const parsed = parseSQLFile(cleanSql);

	if (parsed.events.length > 0) {
		for (const event of parsed.events) {
			console.error(`Parser event (${event.type}):`, event.message);
		}
	}

	const irMap = new Map<string, any>();
	for (const query of parsed.queries) {
		const ir = queryASTToIR(query);
		irMap.set(query.name, ir);
	}

	const code: string[] = [];

	code.push('/**',
		' * BrewMesh Typed Database Queries',
		' * Generated automatically from sql/queries.sql via scripts/queries-typegen.ts.',
		' * Do not edit this file manually.',
		' */',
		'',
		"import { PreparedQuery } from '@pgtyped/runtime';",
		'',
		'export type UserRole = \'customer\' | \'owner\';',
		'export type ItemCategory = \'Coffee\' | \'Tea & Coolers\' | \'Burgers & Sandwiches\' | \'Chips & Sides\';',
		'export type OrderStatus = \'Pending\' | \'Preparing\' | \'Ready\' | \'Completed\';',
		'export type OrderChannel = \'web_ui\' | \'webmcp_agent\' | \'mcp_server\';',
		'export type VibeRating = \'Amazing\' | \'Cozy\' | \'Productive\' | \'Too Cold\' | \'Noisy\';',
		'',
		'export interface User {',
		'\tid: string;',
		'\tname: string;',
		'\trole: UserRole;',
		'\tavatar: string;',
		'\twalletBalance: number;',
		'\tisDiscoverable: boolean;',
		'\ttableLabel: string | null;',
		'\tstatusBlurb: string | null;',
		'\tcurrentItemSummary: string | null;',
		'\tupdatedAt: string;',
		'}',
		'',
		'export interface CustomizationOption {',
		'\tlabel: string;',
		'\tpriceDelta: number;',
		'}',
		'',
		'export interface CustomizationGroup {',
		'\tname: string;',
		'\trequired?: boolean;',
		'\toptions: CustomizationOption[];',
		'}',
		'',
		'export interface MenuItem {',
		'\tid: number;',
		'\tslug: string;',
		'\tname: string;',
		'\tcategory: ItemCategory;',
		'\tdescription: string;',
		'\tbasePrice: number;',
		'\tstockCount: number;',
		'\tisAvailable: boolean;',
		'\tprepTimeMins: number;',
		'\tcalories: number;',
		'\tcaffeineMg: number;',
		'\ttags: string[];',
		'\tcustomizationGroups: CustomizationGroup[];',
		'}',
		'',
		'export interface OrderItem {',
		'\tmenuItemId: number;',
		'\tname: string;',
		'\tcategory: string;',
		'\tbasePrice: number;',
		'\tunitPrice: number;',
		'\tquantity: number;',
		'\tcustomizations?: Record<string, string>;',
		'\tlineTotal: number;',
		'}',
		'',
		'export interface Order {',
		'\tid: number;',
		'\tuserId: string;',
		'\tuserName: string;',
		'\ttableLabel: string | null;',
		'\titems: OrderItem[];',
		'\ttotalAmount: number;',
		'\tstatus: OrderStatus;',
		'\torderedVia: OrderChannel;',
		'\testimatedWaitMins: number;',
		'\tnotes: string | null;',
		'\tcreatedAt: string;',
		'\tupdatedAt: string;',
		'}',
		'',
		'export interface TableWave {',
		'\tid: number;',
		'\tfromUserId: string;',
		'\tfromName: string;',
		'\tfromTable: string | null;',
		'\ttoUserId: string;',
		'\tmessage: string;',
		'\tcreatedAt: string;',
		'}',
		'',
		'export interface RoomVibe {',
		'\tid: number;',
		'\tuserId: string;',
		'\tuserName: string;',
		'\tvibe: VibeRating;',
		'\tcomment: string;',
		'\tcreatedAt: string;',
		'}',
		'',
		'export interface QueueSummary {',
		'\tactiveOrderCount: number;',
		'\tpendingCount: number;',
		'\tpreparingCount: number;',
		'\treadyCount: number;',
		'\testimatedWaitMins: number;',
		'\tcrowdStatus: \'Quiet\' | \'Moderate\' | \'Busy\';',
		'}',
		'',
		'export interface ViewerContext {',
		'\tuser: User;',
		'\tactiveOrders: Order[];',
		'\torderHistory: Order[];',
		'\tusualItems: MenuItem[];',
		'\tqueueSummary: QueueSummary;',
		'\tincomingWaves: TableWave[];',
		'\tdiscoverableCount: number;',
		'\tcompanionNudge: string | null;',
		'}',
		'',
		'export interface OrderPlacementResult {',
		'\torder: Order;',
		'\twalletBalance: number;',
		'\tqueueSummary: QueueSummary;',
		'\tcompanionNudge: string | null;',
		'}',
		'',
		'export interface TableConnectResult {',
		'\tuser: User;',
		'\tdiscoverablePeople: User[];',
		'}',
		'',
		'export interface DiscoverTableConnectResult {',
		'\tdiscoverableCount: number;',
		'\tpeople: User[];',
		'}',
		'',
		'export interface DashboardAnalytics {',
		'\ttotalRevenueInr: number;',
		'\ttotalOrders: number;',
		'\thumanOrders: number;',
		'\tagentOrders: number;',
		'\taverageOrderValueInr: number;',
		'\tlowStockItems: number;',
		'\ttopCategories: Array<{',
		'\t\tcategory: string;',
		'\t\tcount: number;',
		'\t\trevenue: number;',
		'\t}>;',
		'}',
		'',
		'export interface OwnerDashboard {',
		'\tkitchenQueue: Order[];',
		'\trecentCompleted: Order[];',
		'\tinventory: MenuItem[];',
		'\tanalytics: DashboardAnalytics;',
		'\troomVibes: RoomVibe[];',
		'\tqueueSummary: QueueSummary;',
		'}',
		''
	);

	// Parameter & result interfaces
	code.push(
		'export interface IGetViewerContextParams {',
		'\tuserId: string;',
		'}',
		'export interface IGetViewerContextResult {',
		'\tresult: ViewerContext;',
		'}',
		'',
		'export interface IListMenuItemsParams {',
		'\tcategory?: ItemCategory | string | null;',
		'\tquery?: string | null;',
		'\tonlyAvailable?: boolean | null;',
		'}',
		'export interface IListMenuItemsResult {',
		'\tresult: MenuItem[];',
		'}',
		'',
		'export interface ITopUpWalletParams {',
		'\tuserId: string;',
		'\tamount?: number | null;',
		'}',
		'export interface ITopUpWalletResult {',
		'\tresult: ViewerContext;',
		'}',
		'',
		'export interface IPlaceOrderParams {',
		'\tuserId: string;',
		'\titems: any;',
		'\torderedVia?: OrderChannel | string | null;',
		'\tnotes?: string | null;',
		'}',
		'export interface IPlaceOrderResult {',
		'\tresult: OrderPlacementResult;',
		'}',
		'',
		'export interface ISetTableConnectParams {',
		'\tuserId: string;',
		'\tisDiscoverable: boolean;',
		'\ttableLabel?: string | null;',
		'\tstatusBlurb?: string | null;',
		'}',
		'export interface ISetTableConnectResult {',
		'\tresult: TableConnectResult;',
		'}',
		'',
		'export interface IDiscoverTableConnectParams {',
		'\tviewerId: string;',
		'\tquery?: string | null;',
		'}',
		'export interface IDiscoverTableConnectResult {',
		'\tresult: DiscoverTableConnectResult;',
		'}',
		'',
		'export interface ISendTableWaveParams {',
		'\tfromUserId: string;',
		'\ttoUserId: string;',
		'\tmessage: string;',
		'}',
		'export interface ISendTableWaveResult {',
		'\tresult: TableWave;',
		'}',
		'',
		'export interface ISubmitRoomVibeParams {',
		'\tuserId: string;',
		'\tvibe: VibeRating | string;',
		'\tcomment: string;',
		'}',
		'export interface ISubmitRoomVibeResult {',
		'\tresult: RoomVibe;',
		'}',
		'',
		'export interface IAdvanceOrderStatusParams {',
		'\torderId: number;',
		'\tstatus: OrderStatus | string;',
		'}',
		'export interface IAdvanceOrderStatusResult {',
		'\tresult: Order;',
		'}',
		'',
		'export interface IUpdateMenuStockParams {',
		'\titemId: number;',
		'\tstockDelta?: number | null;',
		'\tabsoluteStock?: number | null;',
		'\tisAvailable?: boolean | null;',
		'}',
		'export interface IUpdateMenuStockResult {',
		'\tresult: MenuItem;',
		'}',
		'',
		'export interface IGetOwnerDashboardParams {',
		'\t[key: string]: never;',
		'}',
		'export interface IGetOwnerDashboardResult {',
		'\tresult: OwnerDashboard;',
		'}',
		'',
		'export interface IListTableGamesParams {',
		'\tsource?: string | null;',
		'\tonlyLookingForPlayers?: boolean | null;',
		'}',
		'export interface IListTableGamesResult {',
		'\tresult: { games: any[] };',
		'}',
		'',
		'export interface ICreateOrJoinGameParams {',
		'\taction?: string | null;',
		'\tgameId?: string | null;',
		'\tuserId: string;',
		'\ttitle?: string | null;',
		'\tcategory?: string | null;',
		'\tsource?: string | null;',
		'\ttableNumber?: number | null;',
		'\tmaxPlayers?: number | null;',
		'\tnote?: string | null;',
		'}',
		'export interface ICreateOrJoinGameResult {',
		'\tresult: { game: any };',
		'}',
		'',
		'export interface IFindNearbyCafesParams {',
		'\tsearch?: string | null;',
		'\tgame?: string | null;',
		'\tcraving?: string | null;',
		'\tminChatPartners?: number | null;',
		'}',
		'export interface IFindNearbyCafesResult {',
		'\tresult: { cafes: any[]; summary: string };',
		'}',
		''
	);

	// Prepared queries
	const queryNames = [
		'getViewerContext',
		'listMenuItems',
		'topUpWallet',
		'placeOrder',
		'setTableConnect',
		'discoverTableConnect',
		'sendTableWave',
		'submitRoomVibe',
		'advanceOrderStatus',
		'updateMenuStock',
		'getOwnerDashboard',
		'listTableGames',
		'createOrJoinGame',
		'findNearbyCafes'
	];

	for (const name of queryNames) {
		const ir = irMap.get(name);
		if (!ir) {
			throw new Error(`Missing query in parsed sql/queries.sql: ${name}`);
		}
		const paramsType = `I${capitalize(name)}Params`;
		const resultType = `I${capitalize(name)}Result`;

		code.push(
			`const ${name}IR: any = ${JSON.stringify(ir, null, '\t')};`,
			'',
			`/**`,
			` * Execute ${name} query.`,
			` * For example: const [row] = await ${name}.run(params, client);`,
			` */`,
			`export const ${name} = new PreparedQuery<${paramsType}, ${resultType}>(${name}IR);`,
			''
		);
	}

	fs.mkdirSync(path.dirname(outputTsPath), { recursive: true });
	fs.writeFileSync(outputTsPath, code.join('\n'), 'utf8');
	console.log(`Generated typed queries at ${outputTsPath}`);
}

// Execute generator
generateQueries();
